#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const os=require("node:os");
const path=require("node:path");
const {spawnSync}=require("node:child_process");
const {parseLegacyChain}=require("./convert-legado-rules");
const root=path.resolve(__dirname,"..");
const fixture=path.join(root,"tests/fixtures/legado-converter.json");
const temp=fs.mkdtempSync(path.join(os.tmpdir(),"legado-ir-"));
const output=path.join(temp,"report.json");
try{
 const run=spawnSync(process.execPath,[path.join(__dirname,"convert-legado-rules.js"),fixture,"--output="+output],{encoding:"utf8"});
 assert.equal(run.status,0,run.stderr||run.stdout);
 const report=JSON.parse(fs.readFileSync(output,"utf8"));
 assert.equal(report.sourceCount,2);
 assert.equal(report.sources[0].groups.search.fields.name.selector.engine,"legado-chain");
 assert.equal(report.sources[0].groups.bookInfo.fields.name.selector.query,'meta[property="og:title"]');
 assert.equal(report.sources[0].groups.content.fields.content.selector.engine,"css");
 assert.equal(report.sources[1].groups.search.fields.name.status,"manual");
 assert.equal(report.sources[1].groups.search.fields.name.reason,"script-or-template");
 const dotted=parseLegacyChain("class.chapter.title@html");
 assert.equal(dotted.status,"candidate");
 assert.deepEqual(dotted.selector.steps,[{kind:"class",name:"chapter.title",index:null}]);
 assert.equal(dotted.selector.output,"html");
 const ownText=parseLegacyChain("class.content.0@ownText");
 assert.equal(ownText.status,"candidate");
 assert.equal(ownText.selector.output,"owntext");
 const textNodes=parseLegacyChain("tag.p.0@textNodes");
 assert.equal(textNodes.status,"candidate");
 assert.equal(textNodes.selector.output,"textnodes");
 const indexed=parseLegacyChain("class.chapter.2@text");
 assert.equal(indexed.selector.steps[0].index,2);
 const textMatch=parseLegacyChain("text.小说@text");
 assert.equal(textMatch.status,"candidate");
 assert.deepEqual(textMatch.selector.steps[0],{kind:"text",name:"小说",index:null});
 const children=parseLegacyChain("children@html");
 assert.equal(children.status,"candidate");
 assert.deepEqual(children.selector.steps[0],{kind:"children",name:null,index:null});
 const allMatches=parseLegacyChain("class.book@all");
 assert.equal(allMatches.status,"candidate");
 assert.equal(allMatches.selector.steps[0].index,null);
 assert.equal(allMatches.selector.output,"all");
 const reversed=parseLegacyChain("-class.chapter@text");
 assert.equal(reversed.status,"candidate");
 assert.equal(reversed.selector.reverse,true);
 const valueTag=parseLegacyChain("class.book@value");
 assert.equal(valueTag.status,"candidate");
 assert.equal(valueTag.selector.steps[0].name,"book");
 assert.equal(valueTag.selector.steps[1].name,"value");
 const unknownSelector=parseLegacyChain("@xpath://div");
 assert.equal(unknownSelector.status,"manual");
 assert.equal(unknownSelector.reason,"unsupported-xpath");
 const bareTag=parseLegacyChain("a@href");
 assert.equal(bareTag.status,"candidate");
 assert.deepEqual(bareTag.selector.steps[0],{kind:"tag",name:"a",index:null});
 const implicitText=parseLegacyChain("div@a");
 assert.equal(implicitText.status,"candidate");
 assert.deepEqual(implicitText.selector.steps[0],{kind:"tag",name:"div",index:null});
 assert.equal(implicitText.selector.output,"text");
 const chainedBareTags=parseLegacyChain("div@a@text");
 assert.equal(chainedBareTags.status,"candidate");
 assert.deepEqual(chainedBareTags.selector.steps.map(x=>x.name),["div","a"]);
 const jsonPath=parseLegacyChain("@json:$.items");
 assert.equal(jsonPath.status,"manual");
 assert.equal(jsonPath.reason,"unsupported-jsonpath");
 const implicitIndex=parseLegacyChain("head@.1@text");
 assert.equal(implicitIndex.status,"candidate");
 assert.deepEqual(implicitIndex.selector.steps[1],{kind:"children",name:null,index:1});
 const bracketIndex=parseLegacyChain("tag.div[1]@text");
 assert.equal(bracketIndex.selector.steps[0].index,1);
 const includeIndices=parseLegacyChain("tag.div[0,2,4]@text");
 assert.deepEqual(includeIndices.selector.steps[0].selection,{mode:"include",indices:[0,2,4]});
 const excludeIndices=parseLegacyChain("tag.div[!0,2]@text");
 assert.deepEqual(excludeIndices.selector.steps[0].selection,{mode:"exclude",indices:[0,2]});
 const rangeIndices=parseLegacyChain("tag.div[0:10:2]@text");
 assert.deepEqual(rangeIndices.selector.steps[0].selection,{mode:"range",start:0,end:10,step:2});
 const excludeSuffix=parseLegacyChain("tag.div!0:2@text");
 assert.deepEqual(excludeSuffix.selector.steps[0].selection,{mode:"exclude",indices:[0,2]});
 const implicitBracket=parseLegacyChain("head@[1]@text");
 assert.deepEqual(implicitBracket.selector.steps[1],{kind:"children",name:null,index:1});
 const unsupportedAttribute=parseLegacyChain("a[href]@text");
 assert.equal(unsupportedAttribute.status,"manual");
 assert.equal(unsupportedAttribute.reason,"unsupported-attribute-filter");
 const andExpression=parseLegacyChain("class.title&&class.name@text");
 assert.equal(andExpression.status,"manual");
 assert.equal(andExpression.reason,"compound-or-transform-expression");
 assert.deepEqual(andExpression.expression.operators,["&&"]);
 assert.equal(andExpression.expression.operandCount,2);
 const orExpression=parseLegacyChain("class.title||class.name@text");
 assert.deepEqual(orExpression.expression.operators,["||"]);
 const alternateExpression=parseLegacyChain("class.a%%class.b");
 assert.deepEqual(alternateExpression.expression.operators,["%%"]);
 const regexExpression=parseLegacyChain("class.title##\\\\s+## ");
 assert.equal(regexExpression.status,"manual");
 assert.equal(regexExpression.expression.kind,"regex-transform-or-compound");
 assert.equal(regexExpression.expression.regexDelimiterCount,2);
 const onlyOneRegex=parseLegacyChain("class.title##x##y###");
 assert.equal(onlyOneRegex.expression.onlyOne,true);
 assert.equal(onlyOneRegex.expression.regexDelimiterCount,3);
 const quotedOperator=parseLegacyChain('a[href="x&&y"]@text');
 assert.equal(quotedOperator.status,"manual");
 assert.equal(quotedOperator.reason,"unsupported-attribute-filter");
 console.log("Legado converter fixture tests passed.");
}finally{fs.rmSync(temp,{recursive:true,force:true});}
